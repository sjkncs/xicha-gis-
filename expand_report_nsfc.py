from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Pt
from docx.table import Table
from docx.text.paragraph import Paragraph


ROOT = Path.cwd()
DOC = ROOT / "报告_final.docx"
FONT_CN = "宋体"
FONT_EN = "Times New Roman"


def set_run_font(run, size: float | None = None, bold: bool | None = None) -> None:
    if size is not None:
        run.font.size = Pt(size)
    if bold is not None:
        run.font.bold = bold
    run.font.name = FONT_EN
    r_pr = run._element.get_or_add_rPr()
    r_fonts = r_pr.rFonts
    if r_fonts is None:
        r_fonts = OxmlElement("w:rFonts")
        r_pr.append(r_fonts)
    r_fonts.set(qn("w:eastAsia"), FONT_CN)
    r_fonts.set(qn("w:ascii"), FONT_EN)
    r_fonts.set(qn("w:hAnsi"), FONT_EN)


def normalize_para(p, size: float = 10.5, first_line: bool = True) -> None:
    for run in p.runs:
        set_run_font(run, size=size)
    try:
        p.paragraph_format.first_line_indent = Pt(21) if first_line else Pt(0)
        p.paragraph_format.line_spacing = 1.25
        p.paragraph_format.space_after = Pt(3)
    except Exception:
        pass


def set_text(p, text: str, size: float = 10.5, align=None, first_line: bool = True) -> None:
    p.clear()
    run = p.add_run(text)
    set_run_font(run, size=size)
    if align is not None:
        p.alignment = align
    normalize_para(p, size=size, first_line=first_line)


def insert_paragraph_after_element(doc, el, text: str, style=None, size: float = 10.5, align=None, first_line: bool = True):
    p = doc.add_paragraph(style=style)
    set_text(p, text, size=size, align=align, first_line=first_line)
    body = p._p.getparent()
    body.remove(p._p)
    el.addnext(p._p)
    return p


def insert_after_paragraph(doc, p, text: str, style=None, size: float = 10.5, align=None, first_line: bool = True):
    return insert_paragraph_after_element(doc, p._p, text, style=style, size=size, align=align, first_line=first_line)


def next_block_text(doc, p) -> str:
    node = p._p.getnext()
    while node is not None:
        if node.tag.endswith("p"):
            for q in doc.paragraphs:
                if q._p is node:
                    return q.text.strip()
            return ""
        if node.tag.endswith("tbl"):
            return "[TABLE]"
        node = node.getnext()
    return ""


def replace_first_starting(doc, prefix: str, paragraphs: list[str]) -> bool:
    for p in doc.paragraphs:
        if p.text.strip().startswith(prefix):
            set_text(p, paragraphs[0])
            cursor = p
            for extra in paragraphs[1:]:
                cursor = insert_after_paragraph(doc, cursor, extra)
            return True
    return False


def insert_after_heading_exact(doc, heading: str, paragraphs: list[str]) -> bool:
    for p in doc.paragraphs:
        if p.text.strip() == heading:
            nxt = next_block_text(doc, p)
            if paragraphs and paragraphs[0][:18] in nxt:
                return False
            cursor = p
            for text in paragraphs:
                cursor = insert_after_paragraph(doc, cursor, text)
            return True
    return False


def iter_block_items(parent):
    for child in parent.element.body.iterchildren():
        if child.tag.endswith("p"):
            yield Paragraph(child, parent)
        elif child.tag.endswith("tbl"):
            yield Table(child, parent)


